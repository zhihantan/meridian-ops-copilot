"""Generate the ingestion job from config/sources.yaml into resources/generated/ (T06c): one task per source.

Output is deterministic, so PR diffs show exactly which tasks a config change adds or removes.

    uv run python scripts/gen_jobs.py
"""

from __future__ import annotations

from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "resources" / "generated"
HEADER = "# GENERATED by scripts/gen_jobs.py from config/sources.yaml; do not edit by hand.\n"


def task(source: dict, defaults: dict) -> dict:
    s = {**defaults, **source}
    name = s["name"]
    raw = "/Volumes/${var.catalog}/${resources.schemas.landing.name}/${resources.volumes.raw.name}"
    return {
        "task_key": f"ingest_{name}",
        "description": f"{s['system']} {name} feed into bronze.{name}",
        "environment_key": "default",
        "spark_python_task": {
            "python_file": "../../src/meridian/jobs/generic_ingest.py",
            "parameters": ["--catalog", "${var.catalog}", "--bronze-schema", "${resources.schemas.bronze.name}",
                           "--src-dir", "${workspace.file_path}/src", "--source", name,
                           "--path", f"{raw}/{name}", "--format", s["format"], "--run-id", "{{job.run_id}}"],
        },
    }


def job(config: dict) -> dict:
    return {
        "name": "meridian-ingest-sources",
        "description": "Generated: one task per source feed in config/sources.yaml, each into bronze.<source>",
        "tags": {"project": "meridian-poc", "generated": "true"},
        "schedule": {"quartz_cron_expression": config["schedule"], "timezone_id": config["timezone"]},
        "max_concurrent_runs": 1,
        "environments": [{"environment_key": "default",
                          "spec": {"environment_version": "${var.serverless_environment_version}"}}],
        "tasks": [task(source, config["defaults"]) for source in config["sources"]],
    }


TARGETS = ("dev", "prod")  # staging runs only the integration test and what its dashboard reads


class NoAliases(yaml.SafeDumper):
    """Write each target's copy in full rather than as a YAML alias, so the file reads plainly."""

    def ignore_aliases(self, data):
        return True


def main() -> None:
    config = yaml.safe_load((REPO / "config" / "sources.yaml").read_text())
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "ingest_sources.yml"
    jobs = {"ingest_sources": job(config)}
    body = {"targets": {t: {"resources": {"jobs": jobs}} for t in TARGETS}}
    path.write_text(HEADER + yaml.dump(body, Dumper=NoAliases, sort_keys=False, width=120))
    for stale in set(OUT.glob("*.yml")) - {path}:
        stale.unlink()
        print(f"removed {stale.name}")
    print(f"{path.relative_to(REPO)}: 1 job, {len(config['sources'])} source task(s)")


if __name__ == "__main__":
    main()

"""Daily AI digest of quarantined rows (T05b).

Groups quarantine by rule, then asks a pinned model through ai_query for a summary, likely cause and
suggested fix. Counts come from SQL, never from the model. Rows are stored in obs.dq_digest with
ai_generated = true and human_reviewed = false, posted to Slack for triage, and never written back
into any data table.
"""

from __future__ import annotations

import sys
from pathlib import Path

# Serverless Python file tasks run without __file__, so the bundle passes --src-dir.
sys.path.insert(0, sys.argv[sys.argv.index("--src-dir") + 1] if "--src-dir" in sys.argv
                else str(Path(__file__).resolve().parents[2]))

from pyspark.sql import SparkSession

from meridian.jobs.common import names, parser, post_slack, read_uc_secret

# JSON-schema response format (the DDL struct form is not supported for this model endpoint).
RESPONSE_FORMAT = (
    '{"type": "json_schema", "json_schema": {"name": "dq_digest", "strict": true, "schema": {"type": "object", '
    '"properties": {"summary": {"type": "string"}, "likely_cause": {"type": "string"}, '
    '"suggested_fix": {"type": "string"}}, "required": ["summary", "likely_cause", "suggested_fix"], '
    '"additionalProperties": false}}}'
)
DIGEST_SCHEMA = ("digest_date DATE, dataset STRING, rule STRING, severity STRING, rows BIGINT, sample STRING, "
                 "summary STRING, likely_cause STRING, suggested_fix STRING, model STRING, ai_generated BOOLEAN, "
                 "human_reviewed BOOLEAN, generated_at TIMESTAMP, run_id STRING")


def main() -> None:
    p = parser(__doc__.splitlines()[0])
    p.add_argument("--model", default="databricks-claude-sonnet-4-6")  # ai_query batch rejects Sonnet 5.x (15 Oct)
    p.add_argument("--hours", type=int, default=48)
    p.add_argument("--slack-secret", required=True)
    p.add_argument("--channel", default="#meridian-dq-alerts")
    args = p.parse_args()
    n = names(args)
    spark = SparkSession.builder.getOrCreate()
    window = f"_quarantined_at >= current_timestamp() - INTERVAL {args.hours} HOURS AND reprocessed_at IS NULL"

    groups = spark.sql(f"""
        SELECT 'payments' AS dataset, rule, max(severity) AS severity, count(*) AS rows,
               to_json(slice(collect_list(named_struct('merchant_id', merchant_id, 'amount', amount,
                       'currency', currency, 'rescued', left(_rescued_data, 80),
                       'file', regexp_extract(_source_file, '[^/]+$', 0))), 1, 5)) AS sample
        FROM {n.table('quarantine', 'payments')} LATERAL VIEW explode(_failed_rules) r AS rule
        WHERE {window} GROUP BY rule
        UNION ALL
        SELECT 'customers', rule, max(severity), count(*), to_json(slice(collect_list(customer_id), 1, 5))
        FROM {n.table('quarantine', 'customers')} LATERAL VIEW explode(_failed_rules) r AS rule
        WHERE _quarantined_at >= current_timestamp() - INTERVAL {args.hours} HOURS GROUP BY rule
    """)
    groups.createOrReplaceTempView("groups")
    prompt = ("concat('You review data-quality quarantine for a payments marketplace. Rule: ', rule, "
              "'. Dataset: ', dataset, '. Quarantined rows: ', rows, '. Sample rows (JSON): ', sample, "
              "'. In one sentence each: summarise the issue, give the most likely cause, and suggest a fix. "
              "Do not invent counts.')")
    digest = spark.sql(f"""
        SELECT current_date() AS digest_date, dataset, rule, severity, rows, sample, ai.summary, ai.likely_cause,
               ai.suggested_fix, '{args.model}' AS model, true AS ai_generated, false AS human_reviewed,
               current_timestamp() AS generated_at, '{args.run_id}' AS run_id
        FROM (SELECT *, from_json(ai_query('{args.model}', {prompt}, responseFormat => '{RESPONSE_FORMAT}'),
                                  'summary STRING, likely_cause STRING, suggested_fix STRING') AS ai
              FROM groups)
    """)

    target = n.table("obs", "dq_digest")
    spark.sql(f"CREATE TABLE IF NOT EXISTS {target} ({DIGEST_SCHEMA})")
    digest.write.mode("append").saveAsTable(target)

    lines = [(f"*Meridian DQ digest* ({n.catalog}, last {args.hours}h). Counts are from the data; "
              f"the commentary is AI-generated by {args.model} and *not yet reviewed*.")]
    # Read back what was written (serverless has no .cache()), so ai_query runs once per rule.
    written = spark.sql(f"SELECT * FROM {target} WHERE run_id = '{args.run_id}' ORDER BY dataset, rule")
    for r in written.collect():
        lines.append(f"• `{r['dataset']}.{r['rule']}` ({r['severity']}): {r['rows']} rows. {r['summary']} "
                     f"Likely cause: {r['likely_cause']} Suggested fix: {r['suggested_fix']}")
    post_slack(read_uc_secret(args.slack_secret), args.channel, "\n".join(lines))


if __name__ == "__main__":
    main()
